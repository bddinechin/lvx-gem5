// SoftFloat internal fused multiply-add with an op selector (subProd negates the
// product). The public fW_mulAdd is this with op==0; FFMS needs -(a*b)+c, which
// is op==softfloat_mulAdd_subProd. Declared here to avoid pulling internals.h;
// the symbols are exported by libsoftfloat (s_mulAddF{16,32,64}.c).
extern "C" {
float16_t softfloat_mulAddF16(uint_fast16_t, uint_fast16_t, uint_fast16_t, uint_fast8_t);
float32_t softfloat_mulAddF32(uint_fast32_t, uint_fast32_t, uint_fast32_t, uint_fast8_t);
float64_t softfloat_mulAddF64(uint_fast64_t, uint_fast64_t, uint_fast64_t, uint_fast8_t);
}


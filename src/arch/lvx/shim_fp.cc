/*
 * LVX ISA support for gem5 — Layer B shim: IEEE-754 floating-point helpers.
 * SPDX-License-Identifier: BSD-3-Clause
 * Copyright (C) 2026 Liesme Tech.
 * Benoît Dupont de Dinechin (benoit.dinechin@gmail.com).
 *
 * Implements the f16/f32/f64 operator helpers the MDS-generated behavior bodies
 * call, backed by Berkeley SoftFloat (ext/softfloat, RISC-V specialization —
 * default-NaN, tininess-after-rounding, round-to-odd, and the RISC-V
 * out-of-range float->int saturation values). Per width W in {16,32,64}:
 *   arithmetic  fW_{add,sub,mul,mulAdd,mulnAdd,div,sqrt,rint}
 *   min/max     fW_{min,max,minNum,maxNum}
 *   compare     floatcomp_W  (eight ordered/unordered predicates)
 *   classify    fW_classify  (RISC-V FCLASS)
 *   conversions fW<->integer and the fW<->fW' widen/narrow pairs
 * The three widths are structurally identical (verified: same flag-binding order
 * and operand order per operation), so they are generated by width macros.
 *
 * All operators match RISC-V FP arithmetic exactly (mnemonics aside) -- any
 * divergence would be an LVX ISA spec bug. RISC-V has two min/max families and
 * so does LVX, with the plain/Num names inverted between them:
 *   LVX fW_minNum/fW_maxNum == RISC-V FMIN/FMAX  (IEEE minimumNumber/
 *       maximumNumber: return the numeric operand when one is NaN, canonical NaN
 *       only if both are, -0 < +0, invalid only on signaling NaN) == SoftFloat
 *       fW_min/fW_max.
 *   LVX fW_min/fW_max       == RISC-V FMINM/FMAXM (Zfa; IEEE minimum/maximum:
 *       NaN-PROPAGATING -- either operand NaN yields canonical NaN, still raising
 *       invalid on a signaling NaN).
 * fW_rint is fW_roundToInt with exact=true (RISC-V FROUNDNX: raises inexact).
 * Float->int saturates the RISC-V way (NaN/+ovf -> INT_MAX, -ovf -> INT_MIN;
 * unsigned NaN/+ovf -> UINT_MAX, negative -> 0). floatcomp threads no exception
 * flags (bare bool result, like the integer compares), so it raises no invalid
 * on a NaN -- a limitation of the helper signature, not the boolean result.
 *
 * These are PURE functions of (rounding mode, raw IEEE-754 bits). The generated
 * execute body owns all architectural FP state: it resolves the rounding mode
 * (static `floatmode`, or dynamic `$cs.RM` when floatmode==7), pre-applies the
 * `fnegate` sign flips, reads the current `$cs` sticky flags, ORs in this op's
 * freshly-raised flags, and writes `$cs` back. Each helper only sets SoftFloat's
 * rounding mode, clears the scratch flags, runs the op, and returns the result
 * plus this op's raised flags in the per-op Tuple's exact field order.
 *
 * Core-agnostic (shared by lvx_v1 and lvx_v2): FP semantics are identical across
 * cores (a shared-instruction difference would be an ISA authoring error), and
 * the helper ABI is verified byte-identical between the two cores' generated
 * glue. On lvx_v2 the packed/SIMD FP ops invoke these same scalar helpers.
 */
